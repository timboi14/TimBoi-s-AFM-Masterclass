import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
test.setTimeout(150_000);
const libraryAvailable = fs.existsSync(path.resolve('public/personal-library/catalog.json'));
test.skip(!libraryAvailable, 'Requires the personal library pack; originals are intentionally not in Git.');
const catalogue = libraryAvailable ? JSON.parse(fs.readFileSync(path.resolve('public/personal-library/catalog.json'),'utf8')) : {tasks:[],documents:[]};
const firstQuestion=catalogue.tasks.find((t:any)=>t.kind==='practice');
const firstReading=catalogue.tasks.find((t:any)=>t.kind==='learn');
test.beforeEach(async({page})=>{await page.addInitScript(()=>{localStorage.setItem('tba_onboarding_v1',JSON.stringify({dismissed:true,distance:'month'}));localStorage.setItem('tba_fanName','Tim');localStorage.setItem('tba_sitting_choice','2027-03');});});
test('all current kit questions have complete question and answer ranges',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/study-room?tab=Practice');
 await expect(page.getByRole('heading',{name:`${catalogue.tasks.filter((t:any)=>t.kind==='practice'&&t.status==='current').length} practice tasks`})).toBeVisible({timeout:60000});
 await page.locator('.sl-task-row').filter({hasText:firstQuestion.title}).click();
 await expect(page.getByRole('heading',{name:firstQuestion.title,exact:true})).toBeVisible();
 await expect(page.locator('.sl-extract')).toContainText(firstQuestion.title.split('. ')[1].split(' ·')[0].split(' ')[0],{ignoreCase:true});
 await page.getByRole('button',{name:'Reveal source solution'}).click();
 await expect(page.getByRole('spinbutton',{name:'Page',exact:true})).toHaveValue(String(firstQuestion.answerStart));
 await expect(page.locator('.sl-extract pre')).not.toBeEmpty();
 expect(errors).toEqual([]);
});
test('reading recall and a zero-mark attempt persist and enter the study event log',async({page})=>{
 await page.goto(`/study-room?tab=Learn&task=${firstReading.id}`);
 await page.getByRole('textbox',{name:'Recall notes'}).fill('I can explain the principle, apply it to this case and identify the assumptions.');
 await page.getByRole('button',{name:'Save reading & recall'}).click();
 await expect(page.getByRole('button',{name:'Reading completed'})).toBeDisabled();
 await page.goto(`/study-room?tab=Practice&task=${firstQuestion.id}`);
 await page.getByRole('textbox',{name:'Your answer',exact:true}).fill('My first attempt needs revision. I have identified the relevant requirement but used an incorrect method.');
 await page.getByRole('spinbutton',{name:'Awarded',exact:true}).fill('0');
 await page.getByRole('spinbutton',{name:'Available',exact:true}).fill('20');
 await page.getByRole('textbox',{name:'What lost marks, and how will you fix it?'}).fill('Use the source method and explain the scenario implications. Repeat without looking at the solution.');
 await page.getByRole('button',{name:'Save attempt & schedule retest'}).click();
 await expect(page.locator('.sl-answer [role=status]')).toContainText('Attempt saved');
 await page.reload();
 await expect(page.getByRole('textbox',{name:'Your answer',exact:true})).toHaveValue(/My first attempt/);
 await expect(page.getByText('Attempt history (1)')).toBeVisible();
 const saved=await page.evaluate(()=>Object.entries(localStorage).filter(([k])=>k.startsWith('tba_library_')&&k.endsWith('_v1')));
 expect(JSON.stringify(saved)).toContain('Use the source method');
});
test('AI request includes original question and solution and leaves an advisory score',async({page})=>{
 let payload:any;await page.route('**/api/mark',async route=>{payload=route.request().postDataJSON();await route.fulfill({contentType:'text/plain',body:'Marks awarded: 12 / 20\nUse the source evidence.\nSCORE_JSON: {"awarded":12,"available":20,"points":[]}'});});
 await page.goto(`/study-room?tab=Practice&task=${firstQuestion.id}`);
 await page.getByRole('textbox',{name:'Your answer',exact:true}).fill('A complete response with a justified recommendation and scenario-specific evidence.');
 await page.getByRole('spinbutton',{name:'Available',exact:true}).fill('20');
 await page.getByText('Get source-grounded AI feedback',{exact:true}).click();
 await page.getByRole('button',{name:'Request AI feedback'}).click();
 await expect(page.getByRole('spinbutton',{name:'Awarded',exact:true})).toHaveValue('12');
 expect(payload.modelAnswerExtract.length).toBeGreaterThan(500);expect(payload.partRequirement).toContain('Question PDF page');expect(payload.modelAnswerExtract).toContain('Solution PDF page');
});
test('phone layout, schedule and original source download',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/study-room');
 await expect(page.getByRole('heading',{name:'Your next sessions'})).toBeVisible({timeout:60000});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1);
 await page.getByRole('button',{name:'Sources',exact:true}).click();
 await page.getByRole('button',{name:'Read original & extracts'}).first().click();
 await expect(page.getByRole('link',{name:'Download unchanged original'})).toHaveAttribute('download',catalogue.documents[0].filename);
 await page.screenshot({path:`test-results/${catalogue.subject.toLowerCase()}-study-room-phone.png`,fullPage:true});
});
test('private folder import works when local source serving is unavailable',async({page})=>{
 await page.route('**/personal-library/**',r=>r.fulfill({status:404,body:'Missing'}));
 await page.goto('/study-room');await expect(page.getByRole('heading',{name:'Bring your library onto this device'})).toBeVisible({timeout:60000});
 await page.locator('input[type=file]').setInputFiles(path.resolve('public/personal-library'));
 await expect(page.getByRole('heading',{name:'Your next sessions'})).toBeVisible({timeout:120000});
 await page.reload();await expect(page.getByRole('heading',{name:'Your next sessions'})).toBeVisible();
 await page.goto(`/study-room?tab=Practice&task=${firstQuestion.id}`);
 await expect(page.getByRole('link',{name:'Download unchanged original'})).toBeVisible();
 await expect(page.locator('.sl-extract pre')).not.toBeEmpty();
});
